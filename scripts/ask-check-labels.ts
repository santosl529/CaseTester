// Exact labels for every Haiku ask-check call in batches 33–38 (Phase 1 contract §5, Stream 1 task 2). Free: it reads
// the recorded calls (`itemless_defer` checks in the turn files) and the hand labels in evals/ask-check-labels/labels.json.
//
//   npx tsx scripts/ask-check-labels.ts            check every call has a label, write evals/ask-check-labels/report.md
//   npx tsx scripts/ask-check-labels.ts --seed=<labels-by-n.json>   (one-off) write labels.json from labels numbered in call order
//
// The corpus root is REPLAY_ROOT (default: the main checkout's `Case Interview Runs`).
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { SLICES } from '@/lib/eval/fault-bank-build';
import { readTurnFile } from '@/lib/eval/turn-file';
import { askCheckCalls, labelTables, ASK_LABELS, type AskCall, type AskLabel, type LabelledCall } from '@/lib/eval/ask-check-labels';

const ROOT = process.env.REPLAY_ROOT ?? '/Users/lorenzo/coding/personal-projects/CaseTester/Case Interview Runs';
const DIR = 'evals/ask-check-labels';
const LABELS = path.join(DIR, 'labels.json');
const arg = (k: string) => process.argv.find(a => a.startsWith(`--${k}=`))?.slice(k.length + 3);

function corpusCalls(): AskCall[] {
  const out: AskCall[] = [];
  for (const s of SLICES) {
    const waveDir = path.join(ROOT, 'test runs', s.wave);
    for (const dir of readdirSync(waveDir).filter(d => /^\d\d-/.test(d)).sort()) {
      const f = readdirSync(path.join(waveDir, dir)).find(x => x.endsWith('.turns.jsonl.gz'));
      if (!f) continue;
      out.push(...askCheckCalls(s.tag, dir.slice(0, 2), readTurnFile(path.join(waveDir, dir, f)).turns));
    }
  }
  return out;
}

type LabelFile = Record<string, { ask: string; verdict: string; ids: string[]; label: AskLabel; note: string }>;

function seed(file: string) {
  const byN = JSON.parse(readFileSync(file, 'utf8')) as Record<string, { label: AskLabel; note: string }>;
  const calls = corpusCalls();
  if (calls.length !== Object.keys(byN).length) throw new Error(`${calls.length} calls, ${Object.keys(byN).length} labels`);
  const out: LabelFile = {};
  calls.forEach((c, i) => { const l = byN[String(i + 1)]; out[c.key] = { ask: c.ask, verdict: c.verdict, ids: c.ids, label: l.label, note: l.note }; });
  writeFileSync(LABELS, JSON.stringify(out, null, 1) + '\n');
  console.log(`wrote ${LABELS} (${calls.length} calls)`);
}

const pct = (x: number | null) => x === null ? '—' : `${(100 * x).toFixed(0)}%`;
const NAMES: Record<AskLabel, string> = { correct_item: 'correct item', wrong_item: 'wrong item', correct_none: 'correct none', false_none: 'false none', partly_right: 'partly right', timeout: 'timeout (no verdict)' };

function report() {
  if (!existsSync(LABELS)) throw new Error(`no ${LABELS}`);
  const labels = JSON.parse(readFileSync(LABELS, 'utf8')) as LabelFile;
  const calls = corpusCalls();
  const missing = calls.filter(c => !labels[c.key]).map(c => c.key);
  const extra = Object.keys(labels).filter(k => !calls.some(c => c.key === k));
  const changed = calls.filter(c => labels[c.key] && labels[c.key].ask !== c.ask).map(c => c.key);
  const bad = Object.entries(labels).filter(([, l]) => !(ASK_LABELS as readonly string[]).includes(l.label)).map(([k]) => k);
  if (missing.length || extra.length || changed.length || bad.length) throw new Error(`labels out of step — missing ${missing.join(', ') || 'none'}; extra ${extra.join(', ') || 'none'}; ask changed ${changed.join(', ') || 'none'}; bad label ${bad.join(', ') || 'none'}`);
  const lc: LabelledCall[] = calls.map(c => ({ ...c, label: labels[c.key].label, note: labels[c.key].note }));
  const t = labelTables(lc);
  const L: string[] = ['# Haiku ask-check calls, batches 33–38 — exact labels', '',
    `Generated by \`npx tsx scripts/ask-check-labels.ts\` from the recorded calls (\`itemless_defer\` checks in each run's turn file) and the hand labels in \`labels.json\`. ${calls.length} calls. Labels judge Haiku's verdict against the case ledger (Lorenzo's rule 1: a coarser item that answers the ask counts), not what code then did with it. Precision on positives: strict = correct item ÷ mapped verdicts; lenient = (correct item + partly right) ÷ mapped. False-none rate = false none ÷ "maps to no item" verdicts. Timeouts (no verdict) are counted apart.`, '',
    '| batch | calls | correct item | wrong item | partly right | correct none | false none | timeout | precision (strict / lenient) | false-none rate |',
    '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|'];
  const line = (name: string, r: ReturnType<typeof labelTables>['total']) =>
    `| ${name} | ${r.calls} | ${r.correct_item} | ${r.wrong_item} | ${r.partly_right} | ${r.correct_none} | ${r.false_none} | ${r.timeout} | ${pct(r.precisionStrict)} / ${pct(r.precisionLenient)} | ${pct(r.falseNoneRate)} |`;
  for (const s of SLICES) if (t.byBatch[s.tag]) L.push(line(s.tag, t.byBatch[s.tag]));
  L.push(line('**all**', t.total));
  // The check's prompt changed at round 5b (Task 56; b36 on): before and after.
  const early = labelTables(lc.filter(c => /^b3[345]/.test(c.batch))).total, late = labelTables(lc.filter(c => /^b3[678]/.test(c.batch))).total;
  L.push(line('b33–b35 (before round 5b\'s check prompt)', early), line('b36–b38 (after)', late), '');
  L.push('## Every call', '', '| call | ask | verdict | items | label | note |', '|---|---|---|---|---|---|');
  for (const c of lc) L.push(`| ${c.key} | ${c.ask.replace(/\|/g, '/')} | ${c.verdict} | ${c.ids.join(', ')} | ${NAMES[c.label]} | ${c.note.replace(/\|/g, '/')} |`);
  writeFileSync(path.join(DIR, 'report.md'), L.join('\n') + '\n');
  console.log(L.slice(0, 22).join('\n'));
}

if (arg('seed')) seed(arg('seed')!); else report();
